import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { FLAGS, rot13 } from './ctf-flags.mjs';

const sha = (s) => createHash('sha256').update(s).digest('hex');

const challenges = [
  { id: 'source', title: 'Read the room', hint: 'Developers read the page source. Start with the home page.', sha256: sha(FLAGS.source) },
  { id: 'console', title: 'Loud console', hint: 'Open DevTools on the home page and watch the console. Something there is encoded.', sha256: sha(FLAGS.console) },
  { id: 'terminal', title: 'Secret command', hint: 'The home page terminal has a command that is not in help. Is its output really encrypted?', sha256: sha(FLAGS.terminal) },
  { id: 'robots', title: 'Keep out', hint: 'Which file politely asks crawlers to stay away? Follow it, then decode what you find.', sha256: sha(FLAGS.robots) },
];

const artifacts = { source: FLAGS.source, terminalCipher: rot13(FLAGS.terminal) };

await writeFile('src/data/ctf.json', `${JSON.stringify({ challenges, artifacts }, null, 2)}\n`);
await writeFile(
  'assets/js/ctf-console.js',
  `// Generated by scripts/make-ctf.mjs. Do not edit.\nexport const CONSOLE_HINT = '${Buffer.from(FLAGS.console).toString('base64')}';\n`,
);
await writeFile('vault-7f3a.txt', `${Buffer.from(FLAGS.robots).toString('hex')}\n`);
console.log('ctf files written');
